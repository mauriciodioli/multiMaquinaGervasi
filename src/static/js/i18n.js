  const SUP_LANGS = new Set(["es", "en", "it", "pt", "pl"]);

  function getLang() {
    // 1️⃣ Primero intenta leer desde localStorage
    let v = localStorage.getItem("lang") || "";
    if (SUP_LANGS.has(v)) return v;

    // 2️⃣ Si no hay en localStorage, intenta leer desde cookies
    const langFromCookie = getCookieValue("lang");
    if (langFromCookie && SUP_LANGS.has(langFromCookie)) {
      // Guardar en localStorage para futuras lecturas
      localStorage.setItem("lang", langFromCookie);
      return langFromCookie;
    }

    // 3️⃣ Default a español
    return "es";
  }

  // Función auxiliar para leer cookies
  function getCookieValue(name) {
    const cookies = document.cookie.split(";").map(c => c.trim());
    for (const cookie of cookies) {
      const [key, value] = cookie.split("=");
      if (key === name) return decodeURIComponent(value);
    }
    return null;
  }

  // t("login.titulo") / t("registrarse.errores.correo") / t("sim.header") / t("verificar.titulo")
  // Opcionalmente: t("sim.header", "fallback text")
  function t(key, fallback) {
    const lang = getLang();
    const parts = key.split(".");
    const ns = parts.shift() || "login";  // default a login
    const path = parts;                   // resto de la ruta

    // Navega dict[ns][lang][...path]
    let node = dict?.[ns]?.[lang];
    for (const p of path) node = node?.[p];
    if (node !== undefined) return node;

    // Fallback a español si existe
    node = dict?.[ns]?.["es"];
    for (const p of path) node = node?.[p];
    if (node !== undefined) return node;

    // Si aún no hay traducción, usa el fallback proporcionado o retorna la clave
    return fallback !== undefined ? fallback : `[${key}]`;
  }

  // Función auxiliar para traducir elementos con data-i18n
  function applyTranslations(container = document) {
    container.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      const text = t(key);
      
      if (el.tagName === 'BUTTON') {
        el.textContent = text;
        if (el.hasAttribute('aria-label')) {
          el.setAttribute('aria-label', text);
        }
        if (el.hasAttribute('title')) {
          el.setAttribute('title', text);
        }
      } else {
        el.textContent = text;
      }
    });
  }

  return { t, getLang, applyTranslations, dict };
